function getDateOffset(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
}

function getPreviousMonthDate(day: number = 15): string {
  const d = new Date();
  d.setMonth(d.getMonth() - 1);
  d.setDate(day);
  return d.toISOString().split('T')[0];
}

